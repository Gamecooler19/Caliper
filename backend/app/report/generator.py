"""Report generation: ClassificationResult -> readable report text.

Owns ``generate_report``, the one function this module is responsible
for. It calls Muse Spark (via the shared
``app.meta_api.client.create_response``) to write plain-language prose
summarizing a :class:`~app.classification.models.ClassificationResult`.

The single most important behavior of this function: it never relies on
the model to reproduce the regulatory disclaimer. After the model call
returns, ``result.disclaimer`` is appended verbatim and programmatically
to the generated text every time, so the fixed disclaimer string is
byte-exact in the output regardless of what the model generated -- even
if the model's own prose happens to mention a disclaimer, paraphrase it,
or omit it entirely.
"""

from __future__ import annotations

from app.classification.models import ClassificationResult
from app.meta_api.client import create_response
from app.security.secrets import load_muse_spark_model_id

_REPORT_PROMPT_TEMPLATE = (
    "Write a short, plain-language summary (2-4 sentences, no headings, "
    "no markdown) of this medical device risk classification result, for "
    "a manufacturer or importer preparing a CDSCO submission. State the "
    "risk class, the matched rule, the licensing authority, the "
    "applicable form (or that none applies), and whether clinical "
    "investigation is required and why. Do not add a disclaimer or "
    "caveat of your own -- one will be appended automatically after your "
    "text. Do not invent any fact not given below.\n\n"
    "risk_class: {risk_class}\n"
    "matched_rule_id: {matched_rule_id}\n"
    "applicable_licensing_authority: {applicable_licensing_authority}\n"
    "applicable_form: {applicable_form}\n"
    "clinical_investigation_required: {clinical_investigation_required}\n"
    "clinical_investigation_basis: {clinical_investigation_basis}\n"
)


def _build_prompt(result: ClassificationResult) -> str:
    """Build the report-generation prompt from ``result``'s fields.

    Pure string formatting, no I/O -- kept as a standalone function so
    its output is directly testable without mocking the model call.
    """

    return _REPORT_PROMPT_TEMPLATE.format(
        risk_class=result.risk_class.value,
        matched_rule_id=result.matched_rule_id,
        applicable_licensing_authority=result.applicable_licensing_authority.value,
        applicable_form=(
            result.applicable_form.value if result.applicable_form else "None"
        ),
        clinical_investigation_required=result.clinical_investigation_required,
        clinical_investigation_basis=result.clinical_investigation_basis,
    )


async def generate_report(result: ClassificationResult) -> str:
    """Generate a readable report for ``result``.

    Calls Muse Spark for free-text prose summarizing the classification
    result, then appends ``result.disclaimer`` verbatim and
    programmatically -- never generated by, or trusted to, the model.
    The returned string is always ``"{model prose}\\n\\n{disclaimer}"``,
    so the disclaimer is byte-exact and present even if the model's own
    output is empty, malformed prose, or itself contains different
    disclaimer-like text.

    Propagates :class:`~app.meta_api.client.MetaModelAPIError`,
    :class:`~app.meta_api.client.MetaModelAPIResponseError`, or
    :class:`~app.meta_api.client.MetaModelAPITimeoutError` from the
    underlying model call, unchanged -- a failed model call means no
    report is produced at all, not a report missing its prose.
    """

    model = load_muse_spark_model_id()

    prose = await create_response(
        model,
        [{"type": "input_text", "text": _build_prompt(result)}],
    )

    return f"{prose.strip()}\n\n{result.disclaimer}"
